"""Synthesize this new-topic test using an existing local Kokoro ONNX runtime.

Run with a Python environment containing kokoro-onnx, numpy and soundfile:
  python examples/repo-tour/make-audio.py /absolute/production/directory
       --model-dir /absolute/kokoro-model-directory

Models are external production dependencies, never copied into this repository.
Timing is exact synthesis chunk placement; it is not phoneme/word alignment.
"""
import argparse
import hashlib
import importlib.metadata
import json
import math
from pathlib import Path
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE=Path(__file__).resolve().parent

def sha(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for b in iter(lambda:f.read(1<<20),b''):h.update(b)
    return h.hexdigest()

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('production',type=Path)
    ap.add_argument('--model-dir',type=Path,default=Path.home()/'.local/share/kokoro')
    a=ap.parse_args();p=a.production;audio=p/'audio';audio.mkdir(parents=True,exist_ok=True)
    wav=audio/'narration.wav'
    if wav.exists():ap.error('narration.wav exists; preserve it and choose a fresh production directory')
    plan=json.loads((HERE/'plan.json').read_text())
    model=a.model_dir/'kokoro-v1.0.onnx';voices=a.model_dir/'voices-v1.0.bin'
    tts=Kokoro(str(model),str(voices));rate=24000;pos=0;chunks=[];beats=[]
    def silence(seconds):
        nonlocal pos
        n=round(seconds*rate);chunks.append(np.zeros(n,np.float32));pos+=n
    silence(.30)
    for beat in plan['beats']:
        text=' '.join(beat['lines'])
        data,sr=tts.create(text,voice=plan['voice'],speed=plan['speed'],lang=plan['language'])
        assert sr==rate
        start=pos/rate;chunks.append(data);pos+=len(data);end=pos/rate
        # A real breath, not a uniform multi-second slot. Captions hold through it.
        silence(.34)
        beats.append({**beat,'start':round(start,6),'speech_end':round(end,6),'end':round(pos/rate,6),'text':text})
        print(beat['id'],f'{start:.2f}..{end:.2f}',text,flush=True)
    silence(1.1)
    frames=math.ceil(pos/rate*30);silence(frames/30-pos/rate)
    sf.write(wav,np.concatenate(chunks),rate,subtype='PCM_16')
    timing={'title':plan['title'],'fps':30,'duration':frames/30,'frames':frames,
            'voice':plan['voice'],'language':plan['language'],'speed':plan['speed'],
            'audio_sha256':sha(wav),'timing_source':'exact synthesis chunk placement; no word alignment','beats':beats}
    (HERE/'timing.js').write_text('// Generated by make-audio.py; source media stays outside the checkout.\nwindow.TOUR='+json.dumps(timing,indent=2)+';\n')
    (p/'timing.json').write_text(json.dumps(timing,indent=2)+'\n')
    (p/'script.txt').write_text('\n\n'.join(b['text'] for b in beats)+'\n')
    def stamp(t):
        n=round(t*1000);return f'{n//3600000:02}:{n//60000%60:02}:{n//1000%60:02},{n%1000:03}'
    (p/'captions.srt').write_text('\n\n'.join(f"{i+1}\n{stamp(b['start'])} --> {stamp(b['end'])}\n"+'\n'.join(b['lines']) for i,b in enumerate(beats))+'\n')
    (audio/'identity.json').write_text(json.dumps({'file':wav.name,'sha256':sha(wav),'rate':rate,
        'voice':plan['voice'],'language':plan['language'],'speed':plan['speed'],
        'kokoro_onnx':importlib.metadata.version('kokoro-onnx'),
        'model_sha256':sha(model),'voices_sha256':sha(voices),'purpose':'new-brief human/agent tutorial test'},indent=2)+'\n')
    print('Duration:',frames/30,'seconds;',frames,'frames')

if __name__=='__main__':main()
